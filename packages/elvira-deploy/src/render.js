/** Writes a plan (plan.js) as compose.yml, Kubernetes manifests or a .env file. */
import {toYaml, toYamlStream} from './yaml.js';
import {CATALOG_COMMANDS} from './plan.js';
import {GENERATOR} from './version.js';

const PART_OF = 'evilflowers';

export function header(s, plan, what) {
  const names = plan.services.map((x) => x.name).join(', ');
  return [
    `ELVIRA ${what}, generated by ${GENERATOR}`,
    `Release channel: ${s.channel === 'develop' ? 'development (develop images)' : 'stable (master images)'}`,
    `Services: ${names}`,
    'Secrets live in .env, never in this file.',
  ].join('\n');
}

// ---------------------------------------------------------------- Compose

function composeEnv(service) {
  if (!service.env?.length) return undefined;
  return Object.fromEntries(service.env.map((e) => [e.name, e.secret ? `\${${e.secret}}` : e.value]));
}

function composeMounts(service) {
  const out = (service.mounts ?? []).map((m) => {
    if (m.volume) return `${m.volume}:${m.path}`;
    if (m.bind) return `${m.bind}:${m.path}`;
    return `./${service.fileSecret}/${m.file}:${m.path}:ro`;
  });
  return out.length ? out : undefined;
}

function composeHealth(service) {
  if (service.probe?.cmd) {
    return {test: ['CMD', ...service.probe.cmd], interval: '10s', timeout: '5s', retries: 10};
  }
  if (service.noImageHealthcheck) {
    return {
      '#': 'The image checks /api/v1/status on port 8000, which this container does not serve.',
      disable: true,
    };
  }
  return undefined;
}

function composePorts(service) {
  const out = (service.ports ?? [])
    .filter((p) => p.publish)
    .map((p) => (p.bind ? `${p.bind}:${p.publish}:${p.port}` : `${p.publish}:${p.port}`));
  return out.length ? out : undefined;
}

export function renderCompose(s, plan) {
  const services = {};
  for (const x of plan.services) {
    const deps = x.dependsOn?.length
      ? Object.fromEntries(x.dependsOn.map((d) => [d.name, {condition: d.condition}]))
      : undefined;
    services[x.name] = {
      '#': x.summary,
      image: x.image,
      platform: x.platform,
      restart: x.oneShot ? 'no' : 'unless-stopped',
      command: x.args,
      user: x.runAsRoot ? '0:0' : undefined,
      env_file: x.envFile ? ['.env'] : undefined,
      environment: composeEnv(x),
      ports: composePorts(x),
      volumes: composeMounts(x),
      shm_size: x.shm,
      stop_grace_period: x.grace ? `${x.grace}s` : undefined,
      depends_on: deps,
      healthcheck: composeHealth(x),
    };
  }
  const volumes = Object.fromEntries(plan.volumes.map((v) => [v.name, {}]));
  const doc = {name: 'evilflowers', services, volumes};
  const head = header(s, plan, 'on Docker Compose')
    .split('\n')
    .map((l) => `# ${l}`)
    .join('\n');
  return `${head}\n# Start: docker compose up -d\n\n${toYaml(doc)}`;
}

// ---------------------------------------------------------------- Kubernetes

function labels(name) {
  return {'app.kubernetes.io/name': name, 'app.kubernetes.io/part-of': PART_OF};
}

function k8sEnv(service) {
  if (!service.env?.length) return undefined;
  return service.env.map((e) =>
    e.secret ? {name: e.name, valueFrom: {secretKeyRef: {name: 'evilflowers', key: e.secret}}} : {name: e.name, value: e.value},
  );
}

function k8sMounts(service) {
  const out = (service.mounts ?? [])
    .filter((m) => !m.bind)
    .map((m) =>
      m.volume
        ? {name: m.volume, mountPath: m.path}
        : {name: service.fileSecret, mountPath: m.path, subPath: m.file, readOnly: true},
    );
  if (service.tmp) out.push({name: 'tmp', mountPath: '/tmp'});
  if (service.shm) out.push({name: 'shm', mountPath: '/dev/shm'});
  return out.length ? out : undefined;
}

function k8sVolumes(service) {
  const out = [];
  const seen = new Set();
  for (const m of service.mounts ?? []) {
    if (m.volume && !seen.has(m.volume)) {
      seen.add(m.volume);
      out.push({name: m.volume, persistentVolumeClaim: {claimName: m.volume}});
    }
  }
  if (service.fileSecret) out.push({name: service.fileSecret, secret: {secretName: service.fileSecret}});
  if (service.tmp) out.push({name: 'tmp', emptyDir: {}});
  if (service.shm) out.push({name: 'shm', emptyDir: {medium: 'Memory', sizeLimit: service.shm.replace(/g$/, 'Gi')}});
  return out.length ? out : undefined;
}

function k8sProbes(service) {
  const port = service.probe?.tcp;
  if (!port) return {};
  const out = {
    readinessProbe: {tcpSocket: {port}, periodSeconds: 10},
    livenessProbe: {tcpSocket: {port}, periodSeconds: 30, failureThreshold: 3},
  };
  if (service.probe.startupSeconds) {
    out.startupProbe = {tcpSocket: {port}, periodSeconds: 10, failureThreshold: Math.ceil(service.probe.startupSeconds / 10)};
  }
  return out;
}

function container(service, overrides = {}) {
  return {
    name: overrides.name ?? service.name,
    image: service.image,
    args: overrides.args ?? service.args,
    envFrom: service.envFile ? [{secretRef: {name: 'evilflowers'}}] : undefined,
    env: k8sEnv(service),
    ports: overrides.noPorts ? undefined : service.ports?.map((p) => ({name: p.name, containerPort: p.port})),
    ...(overrides.noProbes ? {} : k8sProbes(service)),
    securityContext: service.runAsRoot ? {runAsUser: 0, runAsGroup: 0} : undefined,
    volumeMounts: k8sMounts(service),
  };
}

function deployment(s, service) {
  const initContainers = service.init
    ? [
        container(service, {
          name: service.init === 'migrate' ? 'migrate' : 'wait-for-migrations',
          args: CATALOG_COMMANDS[service.init],
          noPorts: true,
          noProbes: true,
        }),
      ]
    : undefined;
  const podSpec = {
    terminationGracePeriodSeconds: service.grace,
    initContainers,
    containers: [container(service)],
    volumes: k8sVolumes(service),
  };
  if (service.runAsRoot) {
    podSpec['#'] = 'Runs as root: it creates directories in the data volume that the catalog (root) owns.';
  }
  return {
    apiVersion: 'apps/v1',
    kind: 'Deployment',
    metadata: {name: service.name, namespace: s.namespace, labels: labels(service.name)},
    spec: {
      replicas: 1,
      strategy: {type: 'Recreate'},
      selector: {matchLabels: labels(service.name)},
      template: {
        metadata: {labels: labels(service.name)},
        spec: podSpec,
      },
    },
  };
}

function k8sService(s, service) {
  return {
    apiVersion: 'v1',
    kind: 'Service',
    metadata: {name: service.name, namespace: s.namespace, labels: labels(service.name)},
    spec: {
      selector: labels(service.name),
      ports: service.ports.map((p) => ({name: p.name, port: p.port, targetPort: p.name})),
    },
  };
}

function pvc(s, volume) {
  const shared = volume.users > 1;
  return {
    apiVersion: 'v1',
    kind: 'PersistentVolumeClaim',
    metadata: {name: volume.name, namespace: s.namespace, labels: labels(volume.name)},
    spec: {
      '#': shared
        ? `${volume.note} Mounted by ${volume.users} pods: ReadWriteMany, or ReadWriteOnce with every pod on one node.`
        : volume.note,
      accessModes: [shared ? 'ReadWriteMany' : 'ReadWriteOnce'],
      storageClassName: s.storageClass || undefined,
      resources: {requests: {storage: volume.size}},
    },
  };
}

function ingress(s) {
  return {
    apiVersion: 'networking.k8s.io/v1',
    kind: 'Ingress',
    metadata: {
      name: 'evilflowers',
      namespace: s.namespace,
      labels: labels('evilflowers'),
      '#': 'For ingress-nginx; other controllers have their own names for the same three limits.',
      annotations: {
        'nginx.ingress.kubernetes.io/proxy-body-size': '500m',
        'nginx.ingress.kubernetes.io/proxy-read-timeout': '300',
        'nginx.ingress.kubernetes.io/proxy-send-timeout': '300',
      },
    },
    spec: {
      '#': 'Add ingressClassName and a tls block for your cluster.',
      rules: [
        {
          host: s.domain,
          http: {
            paths: [{path: '/', pathType: 'Prefix', backend: {service: {name: 'evilflowers', port: {name: 'http'}}}}],
          },
        },
      ],
    },
  };
}

export function renderK8s(s, plan) {
  const docs = [];
  for (const v of plan.volumes) docs.push(pvc(s, v));
  for (const x of plan.services) {
    if (x.oneShot) continue; // the migrate step runs as an init container of the beat pod
    docs.push(deployment(s, x));
    if (x.ports?.length) docs.push(k8sService(s, x));
  }
  docs.push(ingress(s));
  const head = [
    header(s, plan, 'on Kubernetes'),
    '',
    `kubectl create namespace ${s.namespace}`,
    `kubectl -n ${s.namespace} create secret generic evilflowers --from-env-file=.env`,
    'kubectl apply -f evilflowers.yaml',
  ].join('\n');
  return toYamlStream(docs, head);
}

// ---------------------------------------------------------------- .env

export function renderEnv(s, plan) {
  const out = [
    `# ELVIRA secrets, generated by ${GENERATOR}.`,
    s.target === 'k8s'
      ? `# Load into the cluster: kubectl -n ${s.namespace} create secret generic evilflowers --from-env-file=.env`
      : '# Keep this file next to compose.yml. Docker Compose reads it on every start.',
    '# Values are unquoted on purpose: kubectl and Docker Compose read them the same way.',
    '# Anything that says change-me is yours to fill in.',
  ];
  let section = null;
  for (const e of plan.envFile) {
    if (e.section !== section) {
      section = e.section;
      out.push('', `# ----- ${section} -----`);
    }
    if (e.note) out.push(`# ${e.note}`);
    out.push(`${e.key}=${e.value}`);
  }
  return `${out.join('\n')}\n`;
}
